def streeborg(M, bits):
    IV = bytes(64) if bits == 512 else bytes([1]) * 64
    h = IV
    N = bytes(64)
    sigma = bytes(64)

    # Этап 2: полные блоки, отрезаются справа
    while len(M) >= 64:
        m = M[-64:]
        M = M[:-64]
        h = g_N(N, h, m)
        N = ((int.from_bytes(N, 'big') + 512) % (1 << 512)).to_bytes(64, 'big')
        sigma = ((int.from_bytes(sigma, 'big') + int.from_bytes(m, 'big')) % (1 << 512)).to_bytes(64, 'big')

    # Этап 3: остаток (может быть пустым)
    rest_bits = len(M) * 8
    m = bytes(63 - len(M)) + b'\x01' + M
    h = g_N(N, h, m)
    N = ((int.from_bytes(N, 'big') + rest_bits) % (1 << 512)).to_bytes(64, 'big')
    sigma = ((int.from_bytes(sigma, 'big') + int.from_bytes(m, 'big')) % (1 << 512)).to_bytes(64, 'big')

    h = g_N(bytes(64), h, N)
    h = g_N(bytes(64), h, sigma)

    return h if bits == 512 else h[:32]

